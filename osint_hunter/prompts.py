def render(template: str, **kw) -> str:
    """安全的模板填值：只替換 @@name@@，不會誤傷 JSON 大括號。"""
    out = template.replace("@@GROUNDING@@", GROUNDING)
    for k, v in kw.items():
        out = out.replace(f"@@{k}@@", str(v))
    return out
